export interface IndianCity {
  city: string;
  state: string;
  /** Lowercased letters only, for matching what the user types. */
  cityKeys: string[];
  stateKey: string;
}

export const toSearchKey = (s: string) => s.toLowerCase().replace(/[^a-z]/g, '');

export const INDIAN_CITIES: IndianCity[] = Object.entries(CITIES_BY_STATE).flatMap(([state, cities]) =>
  cities.map((entry) => {
    const names = entry.split('|');
    return { city: names[0]!, state, cityKeys: names.map(toSearchKey), stateKey: toSearchKey(state) };
  }),
);

const MAX_SUGGESTIONS = 8;

/**
 * "hyd" finds Hyderabad; "aurangabad, bih" narrows to the Bihar one. Names that start with the query rank above
 * names that only contain it.
 */
export function suggestCities(query: string): IndianCity[] {
  const [cityPart = '', statePart = ''] = query.split(',');
  const q = toSearchKey(cityPart);
  const s = toSearchKey(statePart);
  if (!q) return [];
  const ranked: { city: IndianCity; rank: number }[] = [];
  for (const city of INDIAN_CITIES) {
    if (s && !city.stateKey.startsWith(s)) continue;
    if (city.cityKeys.some((key) => key.startsWith(q))) ranked.push({ city, rank: 0 });
    else if (city.cityKeys.some((key) => key.includes(q))) ranked.push({ city, rank: 1 });
  }
  return ranked
    .sort((a, b) => a.rank - b.rank || a.city.city.localeCompare(b.city.city))
    .slice(0, MAX_SUGGESTIONS)
    .map((entry) => entry.city);
}

export const formatCity = (city: IndianCity) => `${city.city}, ${city.state}`;
